/*---------------------------------------------------------------------------/
/  Configurations of FatFs Module
/---------------------------------------------------------------------------*/

#define FFCONF_DEF	80286	/* Revision ID — 必须与 ff.h 中的 FF_DEFINED 一致 */

/*---------------------------------------------------------------------------/
/ Function Configurations
/---------------------------------------------------------------------------*/

/*=============================================================*/
/* FF_FS_READONLY — 读写模式                                    */
/*   0 = 读写模式（可以使用 f_write/f_mkdir/f_unlink 等写操作）  */
/*   1 = 只读模式（裁剪写相关函数，减小代码体积）                */
/*=============================================================*/
#define FF_FS_READONLY	0

/*=============================================================*/
/* FF_FS_MINIMIZE — API 裁剪等级                                */
/*   0 = 全部启用                                               */
/*   1 = 移除 f_stat/f_getfree/f_unlink/f_mkdir/f_truncate     */
/*   2 = 额外移除 f_opendir/f_readdir/f_closedir               */
/*   3 = 额外移除 f_lseek                                       */
/*=============================================================*/
#define FF_FS_MINIMIZE	0

#define FF_USE_FIND		0	/* 文件搜索功能 f_findfirst/f_findnext（0=禁用） */
#define FF_USE_MKFS		0	/* 格式化功能 f_mkfs（开发阶段建议 1） */
#define FF_USE_FASTSEEK	0	/* 快速定位 f_lseek（0=禁用） */
#define FF_USE_EXPAND	0	/* 文件预分配 f_expand（0=禁用） */
#define FF_USE_CHMOD		0	/* 属性修改 f_chmod/f_utime（0=禁用） */
#define FF_USE_LABEL		0	/* 卷标操作 f_getlabel/f_setlabel（0=禁用） */
#define FF_USE_FORWARD	0	/* 数据转发 f_forward（0=禁用） */

#define FF_USE_STRFUNC	0	/* 字符串 I/O 函数 f_gets/f_putc/f_puts/f_printf */
#define FF_PRINT_LLI		1	/* f_printf 支持 long long（需 C99） */
#define FF_PRINT_FLOAT	1	/* f_printf 支持浮点数 */
#define FF_STRF_ENCODE	3	/* 文件字符串编码：3=UTF-8 */

/*---------------------------------------------------------------------------/
/ Locale and Namespace Configurations
/---------------------------------------------------------------------------*/

/*=============================================================*/
/* FF_CODE_PAGE — 代码页（OEM 字符集编码）                      */
/*   936 = 简体中文（DBCS）                                     */
/*   932 = 日文                                                 */
/*   437 = 英文（标准 ASCII，无需 DBCS 支持，体积最小）          */
/*   0   = 包含所有代码页，运行时用 f_setcp() 切换              */
/*=============================================================*/
#define FF_CODE_PAGE	932

/*=============================================================*/
/* FF_USE_LFN — 长文件名支持                                     */
/*   0 = 禁用 LFN，仅支持 8.3 短文件名，无需 ffunicode.c        */
/*   1 = 启用，静态缓冲区（BSS，非线程安全）                     */
/*   2 = 启用，栈上分配（本工程使用，注意栈空间）               */
/*   3 = 启用，堆上分配（需实现 ff_memalloc/ff_memfree）         */
/*                                                              */
/* FF_MAX_LFN — LFN 最大字符数（12~255，满支持设 255）          */
/*=============================================================*/
#define FF_USE_LFN		2
#define FF_MAX_LFN		255

/*=============================================================*/
/* FF_LFN_UNICODE — API 字符串编码                               */
/*   0 = ANSI/OEM（TCHAR = char）                               */
/*   1 = UTF-16（TCHAR = WCHAR）                                */
/*   2 = UTF-8（TCHAR = char，本工程使用）                      */
/*   3 = UTF-32（TCHAR = DWORD）                                */
/*=============================================================*/
#define FF_LFN_UNICODE	2

/*=============================================================*/
/* FF_LFN_BUF / FF_SFN_BUF — FILINFO 中文件名缓冲区大小          */
/*   fname[] 和 altname[] 分别存储长文件名和短文件名              */
/*   注意：必须满足 FF_LFN_BUF >= FF_SFN_BUF 且 FF_SFN_BUF >= 12 */
/*   FF_LFN_BUF = 255 才能读取完整长文件名                       */
/*=============================================================*/
#define FF_LFN_BUF		255
#define FF_SFN_BUF		12

/*=============================================================*/
/* FF_FS_RPATH — 相对路径支持                                    */
/*   0 = 禁用，路径始终从根目录开始（"0:file.txt"）               */
/*   1 = 启用相对路径和 f_chdir/f_chdrive                        */
/*   2 = 额外支持 f_getcwd（获取当前工作目录）                    */
/*=============================================================*/
#define FF_FS_RPATH		0

/*---------------------------------------------------------------------------/
/ Drive/Volume Configurations
/---------------------------------------------------------------------------*/

/*=============================================================*/
/* FF_VOLUMES — 逻辑驱动器数量（1~10）                           */
/*   几个逻辑驱动器就设几，物理驱动器可以多于逻辑驱动器            */
/*   本工程只用一个 SD 卡，设为 1                                */
/*=============================================================*/
#define FF_VOLUMES		1

#define FF_STR_VOLUME_ID		0	/* 是否使用字符串卷标（如 "SD","USB"） */
#define FF_VOLUME_STRS		"RAM","NAND","CF","SD","SD2","USB","USB2","USB3"

#define FF_MULTI_PARTITION	0	/* 多分区支持：0=每个物理驱动器一个卷 */

/*=============================================================*/
/* FF_MIN_SS / FF_MAX_SS — 扇区大小范围（512/1024/2048/4096）   */
/*   SD 卡固定 512 字节，两者都设 512 最省代码                   */
/*   如果 FF_MAX_SS > FF_MIN_SS，disk_ioctl 必须实现             */
/*   GET_SECTOR_SIZE 命令                                       */
/*=============================================================*/
#define FF_MIN_SS		512
#define FF_MAX_SS		4096

#define FF_LBA64		0		/* 64 位 LBA（需 exFAT 支持） */
#define FF_MIN_GPT		0x10000000	/* GPT 分区最小扇区数 */
#define FF_USE_TRIM		0		/* ATA-TRIM 命令（0=禁用） */

/*---------------------------------------------------------------------------/
/ System Configurations
/---------------------------------------------------------------------------*/

#define FF_FS_TINY		0		/* 小缓冲区模式（0=标准，1=精简，省 FF_MAX_SS 字节） */
#define FF_FS_EXFAT		0		/* exFAT 文件系统支持（需 LFN 已启用） */

/*=============================================================*/
/* FF_FS_NORTC — 无 RTC 时的日期时间处理                         */
/*   1 = 禁用 RTC，使用下方固定的 FF_NORTC_xxx 作为文件时间戳     */
/*   0 = 启用 RTC，需实现 get_fattime() 返回实时时间              */
/*=============================================================*/
#define FF_FS_NORTC		1
#define FF_NORTC_MON	1		/* 固定月份 */
#define FF_NORTC_MDAY	1		/* 固定日期 */
#define FF_NORTC_YEAR	2022	/* 固定年份 */

#define FF_FS_NOFSINFO	0		/* FSINFO 信任等级（0=信任，1=全程扫描） */
#define FF_FS_LOCK		0		/* 文件锁（0=禁用，>0=同时打开的最大文件数） */

#define FF_FS_REENTRANT	0		/* 多线程重入支持（FreeRTOS 下可设 1 并实现同步函数） */
#define FF_FS_TIMEOUT	1000	/* 互斥锁超时（单位：系统时钟节拍） */


/*--- End of configuration options ---*/
